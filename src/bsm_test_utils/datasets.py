def _allocate_file_sizes(
    rng: random.Random,
    file_count: int,
    total_bytes: int,
    distribution: SizeDistribution,
) -> List[int]:
    if file_count == 0:
        return []
    if total_bytes == 0:
        return [0] * file_count
    if file_count == 1:
        return [total_bytes]

    weights: List[float] = []
    for i in range(file_count):
        if distribution == "uniform":
            w = 1.0
        elif distribution == "many_small":
            # 90% small weights, 10% moderate weights
            w = (
                rng.uniform(0.1, 0.5)
                if i < int(file_count * 0.9)
                else rng.uniform(2.0, 6.0)
            )
        elif distribution == "few_large":
            # First few files take the bulk of bytes
            w = (
                rng.uniform(25.0, 60.0)
                if i < max(1, file_count // 6)
                else rng.uniform(0.2, 1.0)
            )
        else:  # mixed
            bucket = i % 10
            if bucket == 0:
                w = rng.uniform(15.0, 40.0)
            elif bucket < 4:
                w = rng.uniform(2.0, 6.0)
            else:
                w = rng.uniform(0.05, 0.8)
        weights.append(w)

    weight_sum = sum(weights)
    sizes = [int(total_bytes * (w / weight_sum)) for w in weights]
    remainder = total_bytes - sum(sizes)

    # Distribute remaining bytes deterministically
    for i in range(abs(remainder)):
        idx = i % file_count
        sizes[idx] += 1 if remainder > 0 else -1

    rng.shuffle(sizes)
    return sizes


def _stream_synthetic_file(
    path: Path,
    size: int,
    profile: ContentProfile,
    rng: random.Random,
    compute_hash: bool = True,
    header_prefix: Optional[bytes] = None,
) -> Tuple[int, Optional[str]]:
    hasher = hashlib.sha256() if compute_hash else None
    remaining = size

    # Pre-build a 4 KiB compressible block and a 4 KiB pseudorandom block per file
    comp_line = (
        f"[2026-01-01 12:00:00:000 INFO] Synthetic log/data block seed={rng.randint(0, 999999)}\n"
    ).encode("utf-8")
    comp_tile = (comp_line * ((4096 // len(comp_line)) + 1))[:4096]
    rand_tile = rng.randbytes(4096)

    with open(path, "wb") as f:
        if header_prefix:
            chunk = header_prefix[:remaining] if size > 0 else b""
            if chunk:
                f.write(chunk)
                if hasher:
                    hasher.update(chunk)
                remaining -= len(chunk)

        if profile == "seeded-random":
            while remaining:
                payload = rng.randbytes(min(STREAM_CHUNK_BYTES, remaining))
                f.write(payload)
                if hasher:
                    hasher.update(payload)
                remaining -= len(payload)
            return size, hasher.hexdigest() if hasher else None

        block_index = 0
        while remaining > 0:
            to_write = min(STREAM_CHUNK_BYTES, remaining)
            buf = bytearray()
            while len(buf) < to_write:
                step = min(4096, to_write - len(buf))
                if profile == "compressible":
                    buf.extend(comp_tile[:step])
                elif profile == "random":
                    # Rotate random tile slightly so blocks aren't identical
                    shift = (block_index * 17) % 256
                    rotated = bytes((b ^ shift) for b in rand_tile[:step])
                    buf.extend(rotated)
                else:  # mixed: alternate compressible and random tiles
                    if block_index % 2 == 0:
                        buf.extend(comp_tile[:step])
                    else:
                        shift = (block_index * 31) % 256
                        rotated = bytes((b ^ shift) for b in rand_tile[:step])
                        buf.extend(rotated)
                block_index += 1

            payload = bytes(buf)
            f.write(payload)
            if hasher:
                hasher.update(payload)
            remaining -= len(payload)

    return size, (hasher.hexdigest() if hasher else None)


def _build_component_rel_path(
    component: str,
    index: int,
    spec: DatasetSpec,
    rng: random.Random,
) -> Tuple[str, Optional[bytes]]:
    unicode_suffix = (
        "_\u03b1\u03b2\u03b3_\u30c6\u30b9\u30c8"
        if spec.unicode_names and (index % 5 == 0)
        else ""
    )

    # Build nested subdirectories up to spec.max_depth and spec.fan_out
    depth = (index % spec.max_depth) + 1
    subdirs: List[str] = []
    for d in range(depth - 1):
        branch = (index + d) % spec.fan_out
        subdirs.append(f"sub_{d}_{branch}")
    sub_prefix = "/".join(subdirs)
    if sub_prefix:
        sub_prefix += "/"

    if component == "worlds":
        base = f"worlds/{spec.world_name}/db"
        ext = ".ldb" if index % 4 != 0 else ".log"
        filename = f"{index:06d}{unicode_suffix}{ext}"
        return f"{base}/{sub_prefix}{filename}", SYNTHETIC_DB_NOTICE.encode("utf-8")
    if component == "packs":
        pack_root = "behavior_packs" if index % 2 == 0 else "resource_packs"
        pack_slot = index % max(1, spec.fan_out)
        filename = f"asset_{index:05d}{unicode_suffix}.json"
        return f"{pack_root}/pack_{pack_slot}/{sub_prefix}{filename}", None
    if component == "config":
        filename = f"config_{index:04d}{unicode_suffix}.json"
        return f"config/{sub_prefix}{filename}", None
    # logs
    filename = f"server_{index:05d}{unicode_suffix}.log"
    return f"logs/{sub_prefix}{filename}", None


def create_server_dataset(
    target_dir: Union[str, Path],
    spec: Optional[DatasetSpec] = None,
) -> DatasetResult:
    """
    Generates a synthetic Bedrock server dataset in target_dir according to DatasetSpec.
    Streams bounded chunks, supports reproducible seeds, and returns file/byte counts
    plus an optional TreeInventory.
    """
    effective = (spec or DatasetSpec()).resolved()
    target = Path(target_dir)
    target.mkdir(parents=True, exist_ok=True)

    rng = random.Random(effective.seed)

    # Always write a marker notice in the world db directory explaining synthetic fixtures
    world_db_dir = target / "worlds" / effective.world_name / "db"
    world_db_dir.mkdir(parents=True, exist_ok=True)

    sizes = _allocate_file_sizes(
        rng,
        effective.file_count,
        effective.total_bytes,
        effective.size_distribution,
    )

    components = list(effective.component_weights.keys()) or ["worlds"]
    comp_weights = [effective.component_weights[c] for c in components]

    written_bytes = 0
    for idx, fsize in enumerate(sizes):
        comp = rng.choices(components, weights=comp_weights, k=1)[0]
        rel_path, header_prefix = _build_component_rel_path(comp, idx, effective, rng)
        full_path = target / rel_path
        full_path.parent.mkdir(parents=True, exist_ok=True)

        # Ensure writable if overwriting a previously read-only file
        if full_path.exists():
            os.chmod(full_path, stat.S_IWRITE | stat.S_IREAD)

        actual_size, _ = _stream_synthetic_file(
            full_path,
            size=fsize,
            profile=effective.profile,
            rng=rng,
            compute_hash=False,
            header_prefix=header_prefix,
        )
        written_bytes += actual_size

        if effective.fixed_timestamp is not None:
            os.utime(full_path, (effective.fixed_timestamp, effective.fixed_timestamp))

        if effective.read_only_ratio > 0 and rng.random() < effective.read_only_ratio:
            os.chmod(full_path, stat.S_IREAD)

    empty_dirs: List[str] = []
    for i in range(effective.empty_dir_count):
        suffix = "_\u7a7a" if effective.unicode_names and i % 2 == 1 else ""
        rel_empty = f"worlds/{effective.world_name}/empty_dir_{i:03d}{suffix}"
        empty_path = target / rel_empty
        empty_path.mkdir(parents=True, exist_ok=True)
        if effective.fixed_timestamp is not None:
            try:
                os.utime(
                    empty_path,
                    (effective.fixed_timestamp, effective.fixed_timestamp),
                )
            except OSError:
                pass
        empty_dirs.append(rel_empty)

    symlinks: List[str] = []
    if effective.create_symlinks and effective.file_count > 0:
        first_files = [
            p for p in target.rglob("*") if p.is_file() and not p.is_symlink()
        ]
        if first_files:
            link_rel = "worlds/latest_file_link"
            link_path = target / link_rel
            try:
                if link_path.exists() or link_path.is_symlink():
                    link_path.unlink()
                os.symlink(first_files[0], link_path)
                symlinks.append(link_rel)
            except (OSError, NotImplementedError):
                # Windows without developer mode / elevated privilege may disallow symlinks
                pass

    inventory = (
        build_tree_inventory(target, compute_hashes=effective.compute_hashes)
        if effective.compute_hashes
        else None
    )

    return DatasetResult(
        target_dir=target,
        spec=effective,
        file_count=effective.file_count,
        total_bytes=written_bytes,
        empty_dirs=empty_dirs,
        symlinks=symlinks,
        inventory=inventory,
    )


def _hash_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            chunk = f.read(STREAM_CHUNK_BYTES)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def build_tree_inventory(
    root_dir: Union[str, Path],
    compute_hashes: bool = True,
    include_empty_dirs: bool = True,
) -> TreeInventory:
    """
    Walks root_dir and builds a deterministic TreeInventory of relative paths,
    file sizes, optional SHA-256 digests, timestamps, permissions, and symlinks.
    """
    root = Path(root_dir).resolve()
    entries: Dict[str, FileEntry] = {}
    total_files = 0
    total_bytes = 0
    total_dirs = 0

    for current_root, dirs, files in os.walk(root, followlinks=False):
        dirs.sort()
        files.sort()
        curr_path = Path(current_root)

        # Check directories (and directory symlinks)
        for d in dirs:
            dpath = curr_path / d
            rel = dpath.relative_to(root).as_posix()
            if dpath.is_symlink():
                entries[rel] = FileEntry(
                    rel_path=rel,
                    size=0,
                    is_dir=False,
                    is_symlink=True,
                    symlink_target=os.readlink(dpath),
                )
            else:
                total_dirs += 1
                if include_empty_dirs and not any(dpath.iterdir()):
                    st = dpath.stat()
                    entries[rel] = FileEntry(
                        rel_path=rel,
                        size=0,
                        mtime_ns=st.st_mtime_ns,
                        mode=stat.S_IMODE(st.st_mode),
                        is_dir=True,
                    )

        for fname in files:
            fpath = curr_path / fname
            rel = fpath.relative_to(root).as_posix()
            if fpath.is_symlink():
                entries[rel] = FileEntry(
                    rel_path=rel,
                    size=0,
                    is_dir=False,
                    is_symlink=True,
                    symlink_target=os.readlink(fpath),
                )
            else:
                st = fpath.stat()
                digest = _hash_file(fpath) if compute_hashes else None
                entries[rel] = FileEntry(
                    rel_path=rel,
                    size=st.st_size,
                    sha256=digest,
                    mtime_ns=st.st_mtime_ns,
                    mode=stat.S_IMODE(st.st_mode),
                    is_dir=False,
                )
                total_files += 1
                total_bytes += st.st_size

    return TreeInventory(
        root=root,
        entries=entries,
        total_files=total_files,
        total_bytes=total_bytes,
        total_dirs=total_dirs,
    )


def compare_trees(
    expected: Union[str, Path, TreeInventory],
    actual: Union[str, Path, TreeInventory],
    *,
    check_hashes: bool = True,
    check_mtime: bool = False,
    check_permissions: bool = False,
    include_empty_dirs: bool = True,
    ignore_paths: Optional[Sequence[str]] = None,
) -> TreeComparison:
    """
    Compares an expected directory or TreeInventory against an actual restored directory
    or TreeInventory, identifying missing, extra, and modified entries.
    """
    exp_inv = (
        expected
        if isinstance(expected, TreeInventory)
        else build_tree_inventory(
            expected,
            compute_hashes=check_hashes,
            include_empty_dirs=include_empty_dirs,
        )
    )
    act_inv = (
        actual
        if isinstance(actual, TreeInventory)
        else build_tree_inventory(
            actual,
            compute_hashes=check_hashes,
            include_empty_dirs=include_empty_dirs,
        )
    )

    ignored = {p.replace("\\", "/").strip("/") for p in (ignore_paths or [])}

    exp_keys = {k for k in exp_inv.entries if k not in ignored}
    act_keys = {k for k in act_inv.entries if k not in ignored}

    missing = sorted(exp_keys - act_keys)
    extra = sorted(act_keys - exp_keys)
    changed: Dict[str, str] = {}

    for rel in sorted(exp_keys & act_keys):
        e = exp_inv.entries[rel]
        a = act_inv.entries[rel]

        if e.is_dir != a.is_dir:
            changed[rel] = f"type mismatch (dir={e.is_dir} vs dir={a.is_dir})"
            continue
        if e.is_symlink != a.is_symlink:
            changed[rel] = (
                f"symlink mismatch (symlink={e.is_symlink} vs symlink={a.is_symlink})"
            )
            continue
        if e.is_symlink and e.symlink_target != a.symlink_target:
            changed[rel] = (
                f"symlink target mismatch ({e.symlink_target!r} != {a.symlink_target!r})"
            )
            continue
        if not e.is_dir and not e.is_symlink:
            if e.size != a.size:
                changed[rel] = f"size mismatch (expected {e.size}, got {a.size})"
                continue
            if check_hashes and e.sha256 and a.sha256 and e.sha256 != a.sha256:
                changed[rel] = (
                    f"sha256 mismatch (expected {e.sha256[:12]}..., got {a.sha256[:12]}...)"
                )
                continue
            if check_mtime and e.mtime_ns != a.mtime_ns:
                changed[rel] = (
                    f"mtime_ns mismatch (expected {e.mtime_ns}, got {a.mtime_ns})"
                )
                continue
            if check_permissions and e.mode != a.mode:
                changed[rel] = (
                    f"mode mismatch (expected {oct(e.mode)}, got {oct(a.mode)})"
                )
                continue

    return TreeComparison(missing=missing, extra=extra, changed=changed)


def assert_trees_equal(
    expected: Union[str, Path, TreeInventory],
    actual: Union[str, Path, TreeInventory],
    **kwargs: Any,
) -> TreeComparison:
    """Asserts that two directory trees match, raising AssertionError with details if not."""
    comp = compare_trees(expected, actual, **kwargs)
    if not comp.ok:
        raise AssertionError(f"Directory restore verification failed: {comp.summary()}")
    return comp


def mutate_server_dataset(
    target_dir: Union[str, Path],
    *,
    add_count: int = 2,
    modify_count: int = 2,
    delete_count: int = 1,
    seed: int = 99,
    added_file_bytes: int = 1024,
) -> DatasetMutationSummary:
    """
    Applies a deterministic set of file additions, modifications, and deletions
    to an existing dataset directory to simulate incremental world/server changes
    between backups.
    """
    target = Path(target_dir).resolve()
    rng = random.Random(seed)

    existing_files = sorted(
        p.relative_to(target).as_posix()
        for p in target.rglob("*")
        if p.is_file() and not p.is_symlink()
    )

    deleted: List[str] = []
    for _ in range(min(delete_count, len(existing_files))):
        idx = rng.randrange(len(existing_files))
        rel = existing_files.pop(idx)
        fpath = target / rel
        os.chmod(fpath, stat.S_IWRITE | stat.S_IREAD)
        fpath.unlink()
        deleted.append(rel)

    modified: List[str] = []
    for _ in range(min(modify_count, len(existing_files))):
        idx = rng.randrange(len(existing_files))
        rel = existing_files.pop(idx)
        fpath = target / rel
        os.chmod(fpath, stat.S_IWRITE | stat.S_IREAD)
        with open(fpath, "ab") as f:
            f.write(f"\n# mutated seed={seed}\n".encode("utf-8"))
        modified.append(rel)

    added: List[str] = []
    for i in range(add_count):
        rel = f"worlds/Bedrock level/db/mutated_{seed}_{i:04d}.ldb"
        fpath = target / rel
        fpath.parent.mkdir(parents=True, exist_ok=True)
        _stream_synthetic_file(
            fpath,
            size=added_file_bytes,
            profile="mixed",
            rng=rng,
            compute_hash=False,
            header_prefix=SYNTHETIC_DB_NOTICE.encode("utf-8"),
        )
        added.append(rel)

    return DatasetMutationSummary(
        added=sorted(added),
        modified=sorted(modified),
        deleted=sorted(deleted),
    )


def measure_backup_restore(
    source_dir: Union[str, Path],
    backup_fn: Callable[[Path, int], Optional[Union[str, Path, int]]],
    restore_fn: Callable[[int], Path],
    *,
    runs: int = 1,
    warmup_runs: int = 0,
    verify_restore: bool = True,
    dataset_details: Optional[Dict[str, Any]] = None,
) -> BenchmarkSummary:
    """
    Benchmarks backup and restore callbacks while keeping inventory construction
    and restore verification strictly outside the timed sections.

    :param source_dir: Path to the already-generated server dataset.
    :param backup_fn: Callable(source_dir, iteration_index) -> optional archive Path or byte size.
    :param restore_fn: Callable(iteration_index) -> Path to the restored directory.
    :param runs: Number of measured iterations (>= 1).
    :param warmup_runs: Number of unrecorded warmup iterations before measurement.
    :param verify_restore: Whether to verify the restored tree against source_dir after timing.
    """
    _validate_benchmark_runs(runs, warmup_runs)
    src_path = Path(source_dir).resolve()
    baseline = build_tree_inventory(src_path, compute_hashes=verify_restore)
    measured = []
    for i in range(warmup_runs + runs):
        start = time.perf_counter()
        artifact = backup_fn(src_path, i)
        backed_up = time.perf_counter()
        restored = Path(restore_fn(i))
        finished = time.perf_counter()
        result = _benchmark_result(
            baseline,
            artifact,
            restored,
            backed_up - start,
            finished - backed_up,
            verify_restore,
            i,
        )
        if i >= warmup_runs:
            measured.append(result)
    return _benchmark_summary(baseline, measured, warmup_runs, dataset_details)


async def measure_async_backup_restore(
    source_dir: Union[str, Path],
    backup_fn: Callable[[Path, int], Awaitable[Optional[Union[str, Path, int]]]],
    restore_fn: Callable[[int], Awaitable[Path]],
    *,
    runs: int = 1,
    warmup_runs: int = 0,
    verify_restore: bool = True,
    dataset_details: Optional[Dict[str, Any]] = None,
) -> BenchmarkSummary:
    """Measure async callbacks and verify restored content outside timed sections."""
    _validate_benchmark_runs(runs, warmup_runs)
    src_path = Path(source_dir).resolve()
    baseline = await asyncio.to_thread(
        build_tree_inventory, src_path, compute_hashes=verify_restore
    )
    measured = []
    for i in range(warmup_runs + runs):
        start = time.perf_counter()
        artifact = await backup_fn(src_path, i)
        backed_up = time.perf_counter()
        restored = Path(await restore_fn(i))
        finished = time.perf_counter()
        result = await asyncio.to_thread(
            _benchmark_result,
            baseline,
            artifact,
            restored,
            backed_up - start,
            finished - backed_up,
            verify_restore,
            i,
        )
        if i >= warmup_runs:
            measured.append(result)
    return _benchmark_summary(baseline, measured, warmup_runs, dataset_details)


def _validate_benchmark_runs(runs: int, warmup_runs: int) -> None:
    if runs < 1:
        raise ValueError("runs must be >= 1")
    if warmup_runs < 0:
        raise ValueError("warmup_runs must be >= 0")


def _benchmark_result(
    baseline_inv: TreeInventory,
    backup_artifact: Optional[Union[str, Path, int]],
    restored_dir: Path,
    backup_sec: float,
    restore_sec: float,
    verify_restore: bool,
    i: int,
) -> BenchmarkRunResult:
    backup_sec = max(1e-9, backup_sec)
    restore_sec = max(1e-9, restore_sec)
    archive_bytes: Optional[int] = None
    if isinstance(backup_artifact, int):
        archive_bytes = backup_artifact
    elif isinstance(backup_artifact, (str, Path)):
        art_path = Path(backup_artifact)
        if art_path.is_file():
            archive_bytes = art_path.stat().st_size
        elif art_path.is_dir():
            archive_bytes = sum(
                p.stat().st_size for p in art_path.rglob("*") if p.is_file()
            )

    comp_ratio: Optional[float] = None
    if archive_bytes is not None and baseline_inv.total_bytes > 0:
        comp_ratio = archive_bytes / baseline_inv.total_bytes

    verified_flag: Optional[bool] = None
    if verify_restore:
        comp = compare_trees(baseline_inv, restored_dir, check_hashes=True)
        verified_flag = comp.ok
        if not comp.ok:
            raise AssertionError(
                f"Restore verification failed on iteration {i}: {comp.summary()}"
            )

    mib = baseline_inv.total_bytes / (1024 * 1024)
    return BenchmarkRunResult(
        backup_seconds=backup_sec,
        restore_seconds=restore_sec,
        total_seconds=backup_sec + restore_sec,
        source_files=baseline_inv.total_files,
        source_bytes=baseline_inv.total_bytes,
        archive_bytes=archive_bytes,
        compression_ratio=comp_ratio,
        backup_throughput_mib_s=mib / backup_sec,
        restore_throughput_mib_s=mib / restore_sec,
        verified=verified_flag,
    )


def _benchmark_summary(
    baseline_inv: TreeInventory,
    measured: List[BenchmarkRunResult],
    warmup_runs: int,
    dataset_details: Optional[Dict[str, Any]],
) -> BenchmarkSummary:
    b_times = [r.backup_seconds for r in measured]
    r_times = [r.restore_seconds for r in measured]
    t_times = [r.total_seconds for r in measured]

    env_info = {
        "python_version": platform.python_version(),
        "platform": platform.platform(),
        "system": platform.system(),
        "machine": platform.machine(),
        "processor": platform.processor(),
    }

    return BenchmarkSummary(
        runs=measured,
        warmup_runs=warmup_runs,
        median_backup_seconds=statistics.median(b_times),
        min_backup_seconds=min(b_times),
        max_backup_seconds=max(b_times),
        median_restore_seconds=statistics.median(r_times),
        min_restore_seconds=min(r_times),
        max_restore_seconds=max(r_times),
        median_total_seconds=statistics.median(t_times),
        source_files=baseline_inv.total_files,
        source_bytes=baseline_inv.total_bytes,
        archive_bytes=measured[-1].archive_bytes,
        compression_ratio=measured[-1].compression_ratio,
        environment=env_info,
        dataset_details=dict(dataset_details or {}),
    )
