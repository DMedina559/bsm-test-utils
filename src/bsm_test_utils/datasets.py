@dataclass
class TreeComparison:
    """Detailed comparison between an expected and restored directory tree."""

    missing: List[str] = field(default_factory=list)
    extra: List[str] = field(default_factory=list)
    changed: Dict[str, str] = field(default_factory=dict)

    @property
    def ok(self) -> bool:
        return not (self.missing or self.extra or self.changed)

    def summary(self) -> str:
        if self.ok:
            return "Trees match exactly."
        parts: List[str] = []
        if self.missing:
            parts.append(
                f"Missing ({len(self.missing)}): {', '.join(self.missing[:10])}"
            )
        if self.extra:
            parts.append(f"Extra ({len(self.extra)}): {', '.join(self.extra[:10])}")
        if self.changed:
            changed_desc = [
                f"{p} ({reason})" for p, reason in list(self.changed.items())[:10]
            ]
            parts.append(f"Changed ({len(self.changed)}): {', '.join(changed_desc)}")
        return " | ".join(parts)


