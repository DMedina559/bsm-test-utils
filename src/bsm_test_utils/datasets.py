ContentProfile = Literal["compressible", "random", "mixed", "seeded-random"]
SizeDistribution = Literal["uniform", "many_small", "few_large", "mixed"]
PresetName = Literal["many-small-files", "few-large-files", "mixed-server"]

SYNTHETIC_DB_NOTICE = (
    "SYNTHETIC FIXTURE DATA ONLY: Files in this directory are generated by "
    "bsm-test-utils for backup, restore, and hashing tests. They do not form a "
    "playable Minecraft Bedrock LevelDB world.\n"
)

STREAM_CHUNK_BYTES = 64 * 1024  # 64 KiB bounded streaming writes


@dataclass
class DatasetSpec:
    """Configuration for generating a reproducible synthetic Bedrock server dataset."""

    preset: Optional[PresetName] = None
    file_count: int = 100
    total_bytes: int = 1024 * 1024  # 1 MiB default
    size_distribution: SizeDistribution = "mixed"
    profile: ContentProfile = "mixed"
    seed: int = 42
    max_depth: int = 3
    fan_out: int = 4
    world_name: str = "Bedrock level"
    component_weights: Dict[str, float] = field(
        default_factory=lambda: {
            "worlds": 0.65,
            "packs": 0.20,
            "config": 0.05,
            "logs": 0.10,
        }
    )
    empty_dir_count: int = 2
    unicode_names: bool = False
    fixed_timestamp: Optional[float] = None
    read_only_ratio: float = 0.0
    create_symlinks: bool = False
    compute_hashes: bool = True
    max_files_limit: int = 50_000
    max_bytes_limit: int = 2 * 1024 * 1024 * 1024  # 2 GiB safety limit

    def resolved(self) -> "DatasetSpec":
        """Returns a copy with preset defaults applied where appropriate."""
        spec = DatasetSpec(**asdict(self))
        if spec.preset == "many-small-files":
            if self.file_count == 100:
                spec.file_count = 1_000
            if self.total_bytes == 1024 * 1024:
                spec.total_bytes = 2 * 1024 * 1024
            spec.size_distribution = "many_small"
        elif spec.preset == "few-large-files":
            if self.file_count == 100:
                spec.file_count = 12
            if self.total_bytes == 1024 * 1024:
                spec.total_bytes = 16 * 1024 * 1024
            spec.size_distribution = "few_large"
        elif spec.preset == "mixed-server":
            if self.file_count == 100:
                spec.file_count = 250
            if self.total_bytes == 1024 * 1024:
                spec.total_bytes = 8 * 1024 * 1024
            spec.size_distribution = "mixed"

        if spec.file_count < 0:
            raise ValueError("file_count must be non-negative")
        if spec.total_bytes < 0:
            raise ValueError("total_bytes must be non-negative")
        if spec.file_count > spec.max_files_limit:
            raise ValueError(
                f"Requested file_count ({spec.file_count}) exceeds max_files_limit ({spec.max_files_limit})"
            )
        if spec.total_bytes > spec.max_bytes_limit:
            raise ValueError(
                f"Requested total_bytes ({spec.total_bytes}) exceeds max_bytes_limit ({spec.max_bytes_limit})"
            )
        if spec.max_depth < 1:
            raise ValueError("max_depth must be >= 1")
        if spec.fan_out < 1:
            raise ValueError("fan_out must be >= 1")
        return spec


